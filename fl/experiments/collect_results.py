"""collect_results.py — aggregate every paper-side artefact from
``results/`` into ``results/tables/*.tex`` and ``results/figures/*.pdf``.

This script is pure transformation: no on-chain calls, no FL training,
no MIA. It reads JSON files written by the experiments documented in
``docs/eval-protocol.md`` and emits LaTeX (paper-ready ``\\begin{tabular}``
blocks) and matplotlib PDFs sized for IEEEtran column widths.

Usage::

    python -m fl.experiments.collect_results
    python -m fl.experiments.collect_results --skip-figures      # tables only
    python -m fl.experiments.collect_results --out-dir results/  # default

Outputs (relative to --out-dir):

    tables/table1_unlearning.tex          MIA scores per method
    tables/table2_gas_comparison.tex      per-op gas + USD on both chains
    tables/table3_feature_comparison.tex  ConsentChain vs prior work
    figures/figure1_scalability.pdf       validateRound(N) gas + cost
    figures/figure2_utility_recovery.pdf  per-round test recon, 5 trajectories

Idempotent and safe to re-run.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path
from typing import Any

LOGGER = logging.getLogger("collect_results")

UA_THRESHOLD_FP = 5500  # × 1e-4, the UnlearningOracle default

# Methods to surface in Table 1, in the row order we want for the paper.
# "no_unlearning" reads pre_mia_scores.json; the rest read each
# method's directory.
TABLE1_ROWS: list[tuple[str, str]] = [
    ("no_unlearning", "No unlearning (baseline)"),
    ("gradient_ascent", "Gradient ascent"),
    ("sisa_fed", "SISA-Fed"),
    ("federaser", "FedEraser"),
    ("naive_retrain", "Naive retrain (exact ref.)"),
]


# =====================================================================
# Table 1 — Unlearning effectiveness (MIA scores)
# =====================================================================


def _load_mia(unlearned_root: Path, key: str) -> dict[str, Any]:
    if key == "no_unlearning":
        path = unlearned_root / "pre_mia_scores.json"
    else:
        path = unlearned_root / key / "mia_scores.json"
    if not path.exists():
        raise FileNotFoundError(f"missing MIA artefact: {path}")
    return json.loads(path.read_text())


def render_table1(unlearned_root: Path) -> str:
    rows: list[str] = []
    for key, label in TABLE1_ROWS:
        m = _load_mia(unlearned_root, key)
        shadow = m["shadow_model"]
        lira = m["lira"]
        label_only = m["label_only"]
        accept = all(
            int(s["score_fixed_point"]) < UA_THRESHOLD_FP
            for s in (shadow, lira, label_only)
        )
        accept_str = r"\checkmark" if accept else r"$\times$"
        rows.append(
            "{} & {:.4f} & {:.4f} & {:.4f} & {} \\\\".format(
                label, shadow["score"], lira["score"], label_only["score"], accept_str
            )
        )
    body = "\n".join(rows)
    return (
        r"% Table 1 — Unlearning effectiveness (MIA scores)" "\n"
        r"% generated by fl/experiments/collect_results.py" "\n"
        r"\begin{tabular}{lcccc}" "\n"
        r"\toprule" "\n"
        r"Method & Shadow MIA & LiRA & Label-only & On-chain accept \\" "\n"
        r"\midrule" "\n"
        f"{body}\n"
        r"\bottomrule" "\n"
        r"\end{tabular}" "\n"
    )


# =====================================================================
# Table 2 — Gas comparison (per-DS lifecycle, single-pass + variance)
# =====================================================================

# These are the four ops we report as the per-DS lifecycle: the same
# set captured by the lifecycle-variance ×10 run.
LIFECYCLE_OPS = ["updateModelHash", "grantConsent", "revokeConsent", "submitAttestation"]


def render_table2(blockchain_dir: Path) -> str:
    pc_path = blockchain_dir / "gas_lifecycle_purechain.json"
    amoy_path = blockchain_dir / "gas_lifecycle_amoy.json"
    if not pc_path.exists() or not amoy_path.exists():
        raise FileNotFoundError(
            "missing lifecycle gas variance reports — run E7 lifecycle ×10 first "
            f"(expected {pc_path} and {amoy_path})"
        )
    pc = json.loads(pc_path.read_text())
    amoy = json.loads(amoy_path.read_text())
    amoy_price_usd = amoy.get("nativePriceUsd")
    if amoy_price_usd is None:
        raise ValueError("amoy report missing nativePriceUsd")

    def _row(op_label: str, op_key: str) -> str:
        pc_op = pc["operations"][op_key]
        amoy_op = amoy["operations"][op_key]
        pc_gas = int(pc_op["gasUsed"]["mean"])
        amoy_gas = int(amoy_op["gasUsed"]["mean"])
        amoy_native = int(amoy_op["nativeCostWei"]["mean"]) / 1e18
        amoy_usd = amoy_native * amoy_price_usd
        return "{} & {:,} & {:,} & {:.4f} & \\${:.5f} \\\\".format(
            op_label, pc_gas, amoy_gas, amoy_native, amoy_usd
        )

    op_labels = {
        "updateModelHash": r"\texttt{updateModelHash}",
        "grantConsent": r"\texttt{grantConsent}",
        "revokeConsent": r"\texttt{revokeConsent}",
        "submitAttestation": r"\texttt{submitAttestation} (3-of-5)",
    }
    rows = [_row(op_labels[op], op) for op in LIFECYCLE_OPS]

    # Per-DS aggregate
    pc_per = pc["perDS"]
    amoy_per = amoy["perDS"]
    pc_gas = int(pc_per["gasUsed"]["mean"])
    amoy_gas = int(amoy_per["gasUsed"]["mean"])
    amoy_native = int(amoy_per["nativeCostWei"]["mean"]) / 1e18
    amoy_usd = amoy_native * amoy_price_usd
    aggregate_row = (
        r"\midrule" "\n"
        + r"\textbf{Per-DS lifecycle} & "
        + "\\textbf{{{:,}}} & \\textbf{{{:,}}} & \\textbf{{{:.4f}}} & \\textbf{{\\${:.5f}}} \\\\".format(
            pc_gas, amoy_gas, amoy_native, amoy_usd
        )
    )

    body = "\n".join(rows + [aggregate_row])
    return (
        r"% Table 2 — Per-operation gas + USD (lifecycle ×10 means)" "\n"
        r"% generated by fl/experiments/collect_results.py" "\n"
        r"\begin{tabular}{lrrrr}" "\n"
        r"\toprule" "\n"
        r"Operation & PureChain gas & Amoy gas & Amoy MATIC & Amoy USD \\" "\n"
        r"\midrule" "\n"
        f"{body}\n"
        r"\bottomrule" "\n"
        r"\end{tabular}" "\n"
    )


# =====================================================================
# Table 3 — Feature comparison vs prior work
# =====================================================================
#
# Hand-curated cells. The rest of the LaTeX is mechanical so a typo here
# is fixed in one place.

TABLE3_ROWS = [
    # (system, consent_mgmt, unlearning, verifiable, on_chain, audit, gas_free, method_agnostic)
    ("ConsentChain (ours)", "yes", "yes", "yes", "yes", "yes", "yes", "yes"),
    ("FedEraser (Liu et al. 2021)", "no", "yes", "no", "no", "no", "n/a", "no"),
    ("MedRec (Azaria et al. 2016)", "yes", "no", "no", "yes", "yes", "no", "n/a"),
    ("BlockFL (Kim et al. 2020)", "no", "no", "no", "yes", "yes", "no", "n/a"),
]


def render_table3() -> str:
    def cell(v: str) -> str:
        if v == "yes":
            return r"\checkmark"
        if v == "no":
            return r"$\times$"
        return r"$\sim$"  # n/a / partial

    rows = []
    for system, *cells in TABLE3_ROWS:
        rendered = " & ".join(cell(c) for c in cells)
        rows.append(f"{system} & {rendered} \\\\")
    body = "\n".join(rows)

    return (
        r"% Table 3 — Feature comparison vs prior work" "\n"
        r"% generated by fl/experiments/collect_results.py" "\n"
        r"% Cells: \checkmark = supported, $\times$ = not supported, $\sim$ = n/a or partial" "\n"
        r"\begin{tabular}{lccccccc}" "\n"
        r"\toprule" "\n"
        r"System & Consent & Unlearn & Verifiable & On-chain & Audit & Gas-free & Method-agnostic \\" "\n"
        r"\midrule" "\n"
        f"{body}\n"
        r"\bottomrule" "\n"
        r"\end{tabular}" "\n"
    )


# =====================================================================
# Figure 1 — Scalability sweep
# =====================================================================


def render_figure1(blockchain_dir: Path, out_path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    comp_path = blockchain_dir / "scalability_comparison.json"
    if not comp_path.exists():
        raise FileNotFoundError(f"missing {comp_path}")
    comp = json.loads(comp_path.read_text())
    rows = comp["figure1"]

    Ns = [r["n"] for r in rows]
    pc_gas = [r["pc_gas"] for r in rows]
    amoy_gas = [r["amoy_gas"] for r in rows]
    amoy_usd = [r["amoy_cost_usd"] for r in rows]

    fig, ax_gas = plt.subplots(figsize=(3.5, 2.6), dpi=300)
    ax_gas.plot(Ns, pc_gas, "o-", color="#2A9D8F", label="PureChain gas")
    ax_gas.plot(Ns, amoy_gas, "s-", color="#E76F51", label="Amoy gas")
    ax_gas.set_xlabel("Participants per round (N)")
    ax_gas.set_ylabel("Gas used")
    ax_gas.set_xscale("log")
    ax_gas.set_yscale("log")
    ax_gas.grid(True, which="both", alpha=0.3)
    ax_gas.legend(loc="upper left", fontsize=8)

    ax_usd = ax_gas.twinx()
    ax_usd.plot(Ns, amoy_usd, "^--", color="#264653", label="Amoy USD/round")
    ax_usd.plot(Ns, [0] * len(Ns), "v--", color="#2A9D8F", label="PureChain USD/round")
    ax_usd.set_ylabel("USD per round", color="#264653")
    ax_usd.tick_params(axis="y", labelcolor="#264653")
    ax_usd.set_yscale("symlog", linthresh=1e-5)
    ax_usd.legend(loc="lower right", fontsize=8)

    fig.tight_layout()
    fig.savefig(out_path, format="pdf", bbox_inches="tight")
    plt.close(fig)
    LOGGER.info("wrote %s", out_path)


# =====================================================================
# Figure 2 — Utility recovery
# =====================================================================


def render_figure2(post_revoke_dir: Path, out_path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig2_path = post_revoke_dir / "figure2_dataset.json"
    if not fig2_path.exists():
        raise FileNotFoundError(f"missing {fig2_path}")
    fig2 = json.loads(fig2_path.read_text())

    rounds = fig2["rounds"]
    series = fig2["series"]
    labels = {
        "baseline_9client": "Baseline (9 clients)",
        "post_revoke": "Revoke at r=30 (no unlearn)",
        "post_gradient_ascent": "Gradient ascent + resume",
        "post_sisa_fed": "SISA-Fed + resume",
        "post_federaser": "FedEraser + resume",
    }
    colors = {
        "baseline_9client": "#264653",
        "post_revoke": "#2A9D8F",
        "post_gradient_ascent": "#E9C46A",
        "post_sisa_fed": "#E76F51",
        "post_federaser": "#F4A261",
    }
    styles = {
        "baseline_9client": "-",
        "post_revoke": "--",
        "post_gradient_ascent": ":",
        "post_sisa_fed": "-.",
        "post_federaser": (0, (3, 1, 1, 1)),
    }

    fig, ax = plt.subplots(figsize=(3.5, 2.6), dpi=300)
    for key, label in labels.items():
        if key not in series:
            continue
        ys = series[key]["centralized_test_recon"]
        ax.plot(rounds, ys, linestyle=styles[key], color=colors[key],
                label=label, linewidth=1.4)

    ax.axvline(30, color="black", linestyle=":", linewidth=0.8, alpha=0.6)
    ax.text(30.4, ax.get_ylim()[1] * 0.95, "revoke @ r=30", fontsize=7, alpha=0.7)

    ax.set_xlabel("FL round")
    ax.set_ylabel("Centralized test recon (MSE)")
    ax.set_xlim(1, 40)
    ax.grid(True, alpha=0.3)
    ax.legend(loc="upper right", fontsize=7, frameon=False)

    fig.tight_layout()
    fig.savefig(out_path, format="pdf", bbox_inches="tight")
    plt.close(fig)
    LOGGER.info("wrote %s", out_path)


# =====================================================================
# main
# =====================================================================


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Aggregate experiment JSON → paper assets.")
    p.add_argument("--out-dir", type=Path, default=Path("results"))
    p.add_argument("--skip-figures", action="store_true",
                   help="Render LaTeX tables only; skip matplotlib PDF rendering.")
    args = p.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")

    out_dir = args.out_dir
    tables_dir = out_dir / "tables"
    figures_dir = out_dir / "figures"
    tables_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)

    unlearned_root = out_dir / "nbaiot_unlearned"
    blockchain_dir = out_dir / "blockchain"
    post_revoke_dir = out_dir / "nbaiot_post_revoke"

    # Table 1
    LOGGER.info("rendering Table 1 (unlearning effectiveness)")
    t1 = render_table1(unlearned_root)
    (tables_dir / "table1_unlearning.tex").write_text(t1)

    # Table 2
    LOGGER.info("rendering Table 2 (gas comparison)")
    t2 = render_table2(blockchain_dir)
    (tables_dir / "table2_gas_comparison.tex").write_text(t2)

    # Table 3
    LOGGER.info("rendering Table 3 (feature comparison)")
    t3 = render_table3()
    (tables_dir / "table3_feature_comparison.tex").write_text(t3)

    if not args.skip_figures:
        LOGGER.info("rendering Figure 1 (scalability)")
        render_figure1(blockchain_dir, figures_dir / "figure1_scalability.pdf")
        LOGGER.info("rendering Figure 2 (utility recovery)")
        render_figure2(post_revoke_dir, figures_dir / "figure2_utility_recovery.pdf")

    LOGGER.info("done. tables → %s, figures → %s", tables_dir, figures_dir)
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
